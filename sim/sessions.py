#!/usr/bin/env python3
"""What consecutive draws feel like on a board (docs/ECONOMICS.md section 3). Writes sim/results/sessions.md.

Exact per-draw odds from FWA's rule (weight 1 / price), the board fully restocked, the lead collection NFT at a given
notional, FWA's fee plus its VRF fee at 1 gwei per draw. Each session is N consecutive draws by one player; seeded.
"""
import os
import random
import statistics as st
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from economics import PATTERNS, prize_cost, EDGE, VRF_GAS  # noqa: E402

BOARDS = {
    "launch board (D64: 50 rows), 10%": ("B50", 0.10),
    "the D45 100-row board (launch until D64), 5%": ("D45", 0.05),
    "first Draw Packs board (D42, superseded), 5%": ("D100", 0.05),
    "0.05 ETH board, 7.5%": ("C2", 0.075),
}


def odds(pattern, markup, ape_ref=6.0, ape_notional=6.0, gwei=1.0):
    rows = PATTERNS[pattern]
    prices = [prize_cost(b) * (1 + markup) for b in rows]
    w = {}
    for b, p in zip(rows, prices):
        w[b] = w.get(b, 0.0) + 1 / p
    W = sum(w.values()) + 1 / ape_notional
    ev = (len(rows) + 1) / W
    cost = ev * (1 + EDGE) + VRF_GAS * gwei * 1e-9
    outcomes = sorted(((b, x / W) for b, x in w.items()), key=lambda t: t[0])
    outcomes.append(("APE", (1 / ape_notional) / W))
    return cost, outcomes, ape_ref


def session(rnd, n, cost, outcomes, ape_ref):
    cum = []
    acc = 0.0
    for o, p in outcomes:
        acc += p
        cum.append((acc, o))
    got = []
    for _ in range(n):
        r = rnd.random() * acc
        for c, o in cum:
            if r <= c:
                got.append(o)
                break
    value = sum(ape_ref if o == "APE" else o for o in got)
    return got, value, n * cost


def summarise(name, pattern, markup, sessions=100_000, seed=11):
    cost, outcomes, ape_ref = odds(pattern, markup)
    rnd = random.Random(seed)
    lines = [f"### {name}", "",
             f"Per draw: {cost:.5f} ETH all-in (FWA fee + VRF at 1 gwei). Outcomes per draw: "
             + ", ".join(f"{'collection NFT' if o == 'APE' else f'{o:g} ETH'} {p:.2%}" for o, p in outcomes), "",
             "| draws | spend | returned, median (p10-p90) | net, median | P(back at least the spend) | prizes worth at least FWA fee + VRF (not a profit: gas excluded), median | P(any prize >= 0.05) | P(any >= 0.1) | P(any >= 0.5) | P(any >= 1, the NFT included) | P(collection NFT) | longest run of the cheapest prize, median |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    examples = []
    for n in (10, 20, 50):
        vals, nets, aboves, a05, a01, a5, a1, ape, runs = [], [], [], 0, 0, 0, 0, 0, []
        cheapest = outcomes[0][0]
        for k in range(sessions):
            got, value, spend = session(rnd, n, cost, outcomes, ape_ref)
            vals.append(value)
            nets.append(value - spend)
            aboves.append(sum(1 for o in got if o == "APE" or o >= cost))
            nums = [ape_ref if o == "APE" else o for o in got]
            a05 += any(x >= 0.05 for x in nums)
            a01 += any(x >= 0.1 for x in nums)
            a5 += any(x >= 0.5 for x in nums)
            a1 += any(x >= 1 for x in nums)
            ape += "APE" in got
            best = cur = 0
            for o in got:
                cur = cur + 1 if o == cheapest else 0
                best = max(best, cur)
            runs.append(best)
            if k < 3 and n == 20:
                examples.append(got)
        vals.sort()
        q = lambda xs, p: xs[int(p * (len(xs) - 1))]
        lines.append(
            f"| {n} | {n * cost:.3f} | {st.median(vals):.3f} ({q(vals, .1):.3f}-{q(vals, .9):.3f}) | {st.median(nets):+.3f} | "
            f"{sum(1 for x in nets if x >= 0) / sessions:.1%} | {st.median(aboves):.0f} | {a05 / sessions:.1%} | {a01 / sessions:.1%} | "
            f"{a5 / sessions:.2%} | {a1 / sessions:.2%} | {ape / sessions:.2%} | {st.median(runs):.0f} |")
    lines += ["", "Three random 20-draw sessions (prize per draw, ETH):", ""]
    for got in examples:
        lines.append("- " + " ".join("APE" if o == "APE" else f"{o:g}" for o in got))
    return lines + [""]


def main():
    L = ["# Player sessions", "",
         "Generated by `python3 sim/sessions.py` (seeded, 100,000 sessions per row). The board is fully restocked and the",
         "collection NFT (6 ETH reference) sits at its opening notional, 100% of its price (D59); decay raises its odds.",
         "'Returned' counts prize backing at face value and the NFT at its reference cost. Spend is the FWA fee plus FWA's",
         "VRF fee at 1 gwei; it excludes the player's own transaction gas (~620k gas per draw, ~0.0006 ETH at 1 gwei) and",
         "any redemption gas, so 'back at least the spend' and 'worth at least FWA fee + VRF' are not net profit.", ""]
    for name, (pattern, markup) in BOARDS.items():
        L += summarise(name, pattern, markup)
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    open(os.path.join(HERE, "results", "sessions.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
