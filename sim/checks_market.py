#!/usr/bin/env python3
"""Coin market launch values for the Checks game (D013). Writes sim/results/checks_market.md.

Reuses the exact pool math of sim/launch.py (collection-games): the whole supply single-sided in one v4 position,
fees in ETH, the fixed opening curve (69% falling one point a minute to the ordinary fee). Questions for the values
that are immutable once deployed (the opening tick) or set at launch (ordinary fee, buyback bounds):

1. Activation: the first 80-Check plus the game's opening capital must come from trading fees. How much first-hour
   volume does that need at each fee level, depending on when traders come?
2. Snipers: does a minute-0 buyer lose, at each opening valuation?
3. Depth: how far does a typical buy move the price, and how large a buyback slice fits the burner's 3% impact bound?
4. Buybacks: a released milestone pot of one Check's worth of surplus, burned in slices: how many slices?
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import launch  # noqa: E402

S = launch.S
HERE = os.path.dirname(os.path.abspath(__file__))

CHECK = 0.25  # the 80-Check schedule price at launch (D003)
CAPITAL = 1.666 + 0.5 + 0.2  # 50-row board at cost + reserve + opening keeper allowance (LaunchConfig)
NEED = CHECK + CAPITAL
FDVS = [10, 15, 20, 30.7, 50, 100]
FEES = [0.03, 0.05, 0.10]


def tick_for(fdv):
    """Opening tick: 1.0001^tick coins per ETH, coins per ETH = supply / FDV."""
    return math.log(S / fdv) / math.log(1.0001)


def avg_fee(profile, fee):
    ts = [i / 100 for i in range(0, 6001)]
    if profile == "even":
        w = [1.0] * len(ts)
    elif profile == "rising":
        w = ts
    else:  # traders wait for the end of the curve (minutes 54-60)
        w = [1.0 if t >= 54 else 0.0 for t in ts]
    f = lambda t: max(fee, 0.69 - 0.01 * t)
    return sum(f(t) * wi for t, wi in zip(ts, w)) / sum(w)


def activation_table():
    rows = ["| ordinary fee | volume comes | average fee in hour 1 | hour-1 volume to fund the first Check + capital "
            f"({NEED:.2f} ETH) |", "|---|---|---|---|"]
    for fee in FEES:
        for prof, name in (("even", "evenly"), ("rising", "rising toward minute 60"), ("late", "only at minutes 54-60")):
            a = avg_fee(prof, fee)
            rows.append(f"| {fee:.0%} | {name} | {a:.1%} | {NEED / a:.1f} ETH |")
        rows.append(f"| {fee:.0%} | after the curve | {fee:.0%} | {NEED / fee:.1f} ETH |")
    return rows


def sniper_breakeven(fdv, minute, x=1.0):
    lo, hi = 0.0, 5000.0
    for _ in range(60):
        mid = (lo + hi) / 2
        p = launch.Pool(fdv)
        c = p.buy(x, minute)
        p.buy(mid)
        if p.sell(c) >= x:
            hi = mid
        else:
            lo = mid
    return hi


def depth_table():
    rows = ["| opening FDV | tick | 0.1 ETH buy impact | 1 ETH buy impact | largest buyback within 3% impact | "
            "minute-0 1 ETH buyer: later buying to break even |", "|---|---|---|---|---|---|"]
    for fdv in FDVS:
        cells = []
        for eth in (0.1, 1.0):
            p = launch.Pool(fdv)
            p0 = p.price()
            p.buy(eth)
            cells.append(f"{p.price() / p0 - 1:+.2%}")
        # price impact of an exempt buy of e ETH: (1 + e/x)^2 - 1 <= 3%  =>  e = x (sqrt(1.03) - 1)
        slice_max = fdv * (math.sqrt(1.03) - 1)
        rows.append(f"| {fdv} ETH | {tick_for(fdv):,.0f} | {cells[0]} | {cells[1]} | {slice_max:.3f} ETH | "
                    f"{sniper_breakeven(fdv, 0):.0f} ETH |")
    return rows


def main():
    L = ["# Coin market launch values for the Checks game (D013)", "",
         "Generated by `python3 sim/checks_market.py`, on the pool math of sim/launch.py (collection-games). A model,",
         "not evidence: volumes and timing are assumptions; the math is exact for the single-sided position.", "",
         f"Activation needs the first 80-Check ({CHECK} ETH) plus the opening capital ({CAPITAL:.3f} ETH: the 50-row",
         "board at cost, the 0.5 ETH reserve, the 0.2 ETH opening keeper allowance) from trading fees: "
         f"{NEED:.2f} ETH.", "",
         "## 1. First-hour volume that funds activation", ""] + activation_table() + [""]
    L += ["## 2-3. Depth, buyback slices and snipers by opening valuation", "",
          "Impact is the price move of a buy after the curve. The burner's bound is 3% impact per slice",
          "(`maxImpactBps` 300) and at most 1 ETH. The last column is how much buying after the curve a 1 ETH buyer at",
          "minute 0 (69% fee) needs before selling back at 5% breaks even.", ""] + depth_table() + [""]
    L += ["## Reading", "",
          "- The opening curve does the anti-sniper work at every valuation: a minute-0 buyer needs tens of ETH of",
          "  later buying to break even. The valuation mainly sets depth.",
          "- Depth sets the buyback slice: within the 3% bound a slice can be about 1.5% of the opening FDV. A Check",
          "  win in this game releases a pot of the order of a Check's surplus (fractions of an ETH), so 30 ETH of",
          "  opening FDV (0.45 ETH slices) burns a typical pot in one or two slices; 10 ETH (0.15 ETH slices) needs",
          "  several, each a sandwich opportunity bounded by the 3% deviation check.",
          "- Activation is about 2.6 ETH of fees regardless of the valuation: at 5% and with traders waiting for the",
          "  end of the curve, about 22 ETH of first-hour volume; evenly spread, about 7 ETH.", ""]
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    open(os.path.join(HERE, "results", "checks_market.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
