"""Keeper pay (docs/ECONOMICS.md section 8; D63). Writes sim/results/keepers.md.

The game pays each useful `sync` its measured gas, at the transaction's gas price capped at `maxGasPrice` (3 gwei),
plus a margin (10%): pay = (gasUsed + gasOverhead 70,000) x min(gas price, 3 gwei) x 1.1, within the keeper allowance
(the opening allowance, 0.2 ETH, plus 5% of each captured prize's cost) and never out of cash owed to replacements. A
keeper's transaction costs (gasUsed + 21,000) x gas price. A call with no work reverts; a refill smaller than a row's
cost is not work (no paid loop). Nothing here assumes an unprofitable call: below the cap every call pays its keeper;
the question is whether the allowance keeps up with the gas.

Gas per call is measured on the fork (docs/receipts/gas-prizes.json): booking and replacing k draws in one `sync`.
The odds are the 50-row launch board's (D64), at 10% markup.
"""
import json, math, os, random

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
G = json.load(open(os.path.join(ROOT, "docs", "receipts", "gas-prizes.json")))

MINT_FEE = 0.001
MARKUP = 0.10
# the 50-row launch board (D64): backing -> (rows, Shapes per prize)
BOARD = {0.01: (24, 1), 0.02: (16, 2), 0.03: (3, 3), 0.04: (1, 4), 0.05: (3, 1), 0.1: (1, 1), 0.15: (1, 2), 0.5: (1, 1)}
# FWA picks a listing with probability proportional to 1 / price
_W = {b: n / ((b + k * MINT_FEE) * (1 + MARKUP)) for b, (n, k) in BOARD.items()}
ODDS = {b: w / sum(_W.values()) for b, w in _W.items()}
ONE = {0.01: "shape_001", 0.02: "pack_002", 0.03: "pack_003", 0.04: "pack_004", 0.05: "shape_005", 0.1: "shape_010",
       0.15: "pack_015", 0.5: "shape_050"}
GAS_K = {1: sum(p * G[f"sync_book_1_replace_{ONE[b]}"] for b, p in ODDS.items()),
         3: G["sync_book_3_replace_3"], 5: G["sync_book_5_replace_5"], 8: G["sync_book_8_replace_8"],
         10: G["sync_book_10_replace_10"]}
LIST_MAX = 10  # CollectionGame MAX_LIST_BATCH (D61; the launch board lists 8 per call)
# the keeper allowance a draw earns on average: 5% of the captured prize's cost
ALLOC = 0.05 * sum(p * (b + BOARD[b][1] * MINT_FEE) for b, p in ODDS.items())

# launch keeper parameters (D63)
OVERHEAD = 70_000
CAP = 3.0  # gwei
MARGIN = 0.10
OPENING_ALLOWANCE = 0.2
PRIORITY = 0.02  # gwei, the keeper's priority fee (median paid on mainnet, Oct 2026: ~0.02 gwei)


def gas(k):
    """Measured gas to book and replace k draws in one call (linear between measured batch sizes)."""
    if k <= 0:
        return G["sync_book_1_only"]
    ks = sorted(GAS_K)
    if k in GAS_K:
        return GAS_K[k]
    if k > ks[-1]:
        return GAS_K[10] + (k - 10) * (GAS_K[10] - GAS_K[8]) / 2
    lo = max(x for x in ks if x < k)
    hi = min(x for x in ks if x > k)
    return GAS_K[lo] + (GAS_K[hi] - GAS_K[lo]) * (k - lo) / (hi - lo)


def pay(g, price):
    """The game's payment for a call of measured gas `g` at `price` gwei."""
    return (g + OVERHEAD) * min(price, CAP) * (1 + MARGIN) * 1e-9


def cost(g, price):
    return (g + 21_000) * price * 1e-9


def main():
    L = ["# Keeper pay (sim/keepers.py, D63; the 50-row board, D64)", "",
         f"Generated by `python3 sim/keepers.py`. Pay per useful call = (gas + {OVERHEAD:,}) x min(gas price, {CAP:g} gwei) "
         f"x {1 + MARGIN:.2f}; a keeper pays (gas + 21,000) x gas price (basefee + {PRIORITY} gwei priority). Allowance "
         f"earned per draw: {ALLOC:.6f} ETH (5% of the average captured prize's cost on the 50-row board at 10% markup; "
         f"the cheapest prize is won {ODDS[0.01]:.1%} of draws).", "",
         "## One call: what the keeper earns, and what the allowance can carry", "",
         "Allowance per call: k draws' allowance. Sustainable: pay per call at most the allowance it earns (above it the "
         "allowance runs down and pay stops when it is spent; players' draws through the DrawRouter can still run the "
         "upkeep).", "",
         "| draws booked and replaced per call | gas | basefee | keeper pays | game pays | keeper margin | allowance earned | sustainable |",
         "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for k in (1, 3, 5, 10):
        g = gas(k)
        for bf in (0.1, 0.5, 1.0, 2.0, 3.0, 5.0):
            price = bf + PRIORITY
            p_, c_ = pay(g, price), cost(g, price)
            earned = ALLOC * k
            L.append(f"| {k} | {g:,.0f} | {bf:g} gwei | {c_:.6f} | {p_:.6f} | {p_ - c_:+.6f} | {earned:.6f} | "
                     f"{'yes' if p_ <= earned else 'no'} |")
    L += ["", "## Break-even average gas price for the allowance (pay per draw = allowance per draw)", "",
          "| draws per call | gas per draw | break-even basefee |", "| --- | --- | --- |"]
    for k in (1, 3, 5, 10):
        g = gas(k)
        be = ALLOC * k / ((g + OVERHEAD) * (1 + MARGIN) * 1e-9) - PRIORITY
        L.append(f"| {k} | {g / k:,.0f} | {min(be, CAP):.2f} gwei{' (the cap binds first)' if be > CAP else ''} |")
    open_gas = G.get("sync_fund_and_list_a_batch_of_8", 6_540_555)
    calls = math.ceil(50 / 8)
    L += ["", f"## Listing the opening board ({calls} syncs of about {open_gas / 1e6:.1f}M gas, paid from the "
          f"{OPENING_ALLOWANCE} ETH opening allowance)", "",
          "| basefee | paid for the opening board | share of the opening allowance |", "| --- | --- | --- |"]
    for bf in (0.1, 0.5, 1.0, 3.0, 5.0):
        total = calls * pay(open_gas, bf + PRIORITY)
        L.append(f"| {bf:g} gwei | {total:.4f} ETH | {total / OPENING_ALLOWANCE:.0%} |")
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    open(os.path.join(HERE, "results", "keepers.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
