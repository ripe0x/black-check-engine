// Generates app/lib/abi.generated.ts from the Foundry artifacts (run `forge build` at the repository root first).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
const out = (p) => fileURLToPath(new URL(`../../out/${p}`, import.meta.url));
const pick = {
  lensAbi: "Lens.sol/Lens.json",
  drawRouterAbi: "DrawRouter.sol/DrawRouter.json",
  gameAbi: "CollectionGame.sol/CollectionGame.json",
  vaultAbi: "FundingVault.sol/FundingVault.json",
  poolOwnerAbi: "CollectionPoolOwner.sol/CollectionPoolOwner.json",
  burnerAbi: "CollectionBurner.sol/CollectionBurner.json",
  hookAbi: "CollectionHook.sol/CollectionHook.json",
  liquidityAbi: "ProtocolLiquidity.sol/ProtocolLiquidity.json",
  tokenAbi: "CollectionToken.sol/CollectionToken.json",
  fwaPoolAbi: "IFWA.sol/IFWAPool.json",
  migrationAbi: "MigrationAuthority.sol/MigrationAuthority.json",
  sunsetAbi: "Sunset.sol/Sunset.json",
  adminAbi: "Admin.sol/Admin.json",
  deskAbi: "ChecksDesk.sol/ChecksDesk.json",
};
let ts = "// Generated by scripts/abi.mjs from the Foundry artifacts. Do not edit.\n";
for (const [name, path] of Object.entries(pick)) {
  const p = out(path);
  if (!existsSync(p)) throw new Error(`missing ${p}: run forge build first`);
  ts += `export const ${name} = ${JSON.stringify(JSON.parse(readFileSync(p, "utf8")).abi)} as const;\n`;
}
writeFileSync(fileURLToPath(new URL("../app/lib/abi.generated.ts", import.meta.url)), ts);
console.log("abi: generated");
